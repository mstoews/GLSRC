#!/usr/bin/env python3
"""Build the UI refresh icons (specs/2026-11-13-ui-refresh-design.md 4.2, D2)
from Microsoft's Fluent UI System Icons (MIT).

gl/res/icons/fluent/map.csv says which Fluent icon replaces which bitmap. The
outputs are committed, so the Windows build needs nothing from here:
    gl/res/icons/fluent/<icon>.ico   32-bit, 16 20 24 32 40 48 px
    gl/res/icons/fluent/icons.rc     P<resource> ICON "icons/fluent/<icon>.ico"
    gl/res/icons/fluent/LICENSE      the set's licence, kept with the files
    gl/res/icons/fluent/sheet.png    each old bitmap beside its new icon

usage (from the repository root):
    python3 -I gl/res/tools/make_icons.py fetch <new-empty-dir>
        downloads the regular-style SVGs map.csv names, at the pinned commit,
        and the licence; the downloads are data only, never run
    python3 -I gl/res/tools/make_icons.py build <that-dir>
        renders them (ImageMagick with librsvg) and writes the outputs above
needs: magick (ImageMagick 7, SVG through librsvg), Pillow (sheet only), curl.
"""
import csv, os, struct, subprocess, sys, tempfile

COMMIT = '64e5aa757d1b70c24a283256ddcb8269d0f58773'   # main, 2026-10-28
RAW = f'https://raw.githubusercontent.com/microsoft/fluentui-system-icons/{COMMIT}'
DESIGN = [16, 20, 24, 28, 32, 48]   # the sizes Fluent draws an icon at, where it has them
OUTPUT = [16, 20, 24, 32, 40, 48]   # the sizes in each .ico

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.dirname(HERE)
OUT = os.path.join(RES, 'icons', 'fluent')


def entries():
    with open(os.path.join(OUT, 'map.csv'), newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def snake(name):
    return name.lower().replace(' ', '_')


def svg_name(icon, size):
    return f'ic_fluent_{snake(icon)}_{size}_regular.svg'


def fetch(dest):
    os.makedirs(dest, exist_ok=True)
    if os.listdir(dest):
        sys.exit(f'{dest} is not empty: give a new directory')
    icons = sorted({e['fluent'] for e in entries()})
    for icon in icons:
        got = []
        for size in DESIGN:
            url = f'{RAW}/assets/{icon.replace(" ", "%20")}/SVG/{svg_name(icon, size)}'
            path = os.path.join(dest, svg_name(icon, size))
            r = subprocess.run(['curl', '-sSfL', '-o', path, url])
            if r.returncode == 0:
                got.append(size)
            elif os.path.exists(path):
                os.remove(path)
        if not got:
            sys.exit(f'{icon}: no SVG at {COMMIT}')
        print(f'{icon}: {got}')
    subprocess.run(['curl', '-sSfL', '-o', os.path.join(dest, 'LICENSE'), f'{RAW}/LICENSE'], check=True)


def render(svg, design, size):
    """-> BGRA rows (top-down), size x size."""
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, 'out.rgba')
        density = 96.0 * size / design
        subprocess.run(['magick', '-background', 'none', '-density', f'{density:.4f}', svg,
                        '-resize', f'{size}x{size}!', '-depth', '8', f'rgba:{out}'], check=True)
        data = open(out, 'rb').read()
    if len(data) != size * size * 4:
        sys.exit(f'{svg}: rendered {len(data)} bytes at {size}')
    bgra = bytearray(data)
    bgra[0::4], bgra[2::4] = data[2::4], data[0::4]
    return [bytes(bgra[y * size * 4:(y + 1) * size * 4]) for y in range(size)]


def ico_image(rows, size):
    """A 32-bit DIB icon image: BITMAPINFOHEADER (height doubled), bottom-up
    BGRA, then the AND mask (all 0: the alpha channel decides)."""
    head = struct.pack('<IiiHHIIiiII', 40, size, size * 2, 1, 32, 0, 0, 0, 0, 0, 0)
    xor = b''.join(reversed(rows))
    mask_stride = ((size + 31) // 32) * 4
    return head + xor + bytes(mask_stride * size)


def write_ico(path, images):
    """images: [(size, bytes)]."""
    out = struct.pack('<HHH', 0, 1, len(images))
    offset = 6 + 16 * len(images)
    for size, data in images:
        out += struct.pack('<BBBBHHII', size % 256, size % 256, 0, 0, 1, 32, len(data), offset)
        offset += len(data)
    out += b''.join(d for _, d in images)
    open(path, 'wb').write(out)


def build(src):
    icons = sorted({e['fluent'] for e in entries()})
    for icon in icons:
        have = [s for s in DESIGN if os.path.exists(os.path.join(src, svg_name(icon, s)))]
        if not have:
            sys.exit(f'{icon}: not fetched')
        images = []
        for size in OUTPUT:
            design = min([s for s in have if s >= size] or [max(have)])   # drawn for this size, or the nearest above
            images.append((size, ico_image(render(os.path.join(src, svg_name(icon, design)), design, size), size)))
        write_ico(os.path.join(OUT, snake(icon) + '.ico'), images)
    rc = ['// icons.rc - the UI refresh icons (spec 4.2, D2). Generated by',
          '// gl/res/tools/make_icons.py from map.csv; #included by port.rc. A button',
          '// given bitmap <resource> by SBM_SETPICT shows icon P<resource> instead.',
          f'// Fluent UI System Icons (MIT, see LICENSE), commit {COMMIT}.', '']
    for e in entries():
        rc.append(f'P{e["resource"]:<8} ICON "icons/fluent/{snake(e["fluent"])}.ico"   // {e["used by"]}')
    open(os.path.join(OUT, 'icons.rc'), 'w', encoding='ascii', newline='\r\n').write('\n'.join(rc) + '\n')
    with open(os.path.join(src, 'LICENSE'), 'rb') as f:
        open(os.path.join(OUT, 'LICENSE'), 'wb').write(f.read())
    sheet()
    print(f'{len(icons)} icons, {len(entries())} resources')


def sheet():
    from PIL import Image, ImageDraw
    rows = entries()
    cw, ch, cols = 300, 64, 2
    img = Image.new('RGB', (cw * cols, ch * ((len(rows) + cols - 1) // cols)), (240, 240, 240))
    d = ImageDraw.Draw(img)
    for i, e in enumerate(rows):
        x, y = (i % cols) * cw, (i // cols) * ch
        bmp = os.path.join(RES, 'bitmaps', (e['resource'] if e['resource'] != '4076' else 'ID_SETDATA') + '.bmp')
        old = Image.open(bmp).convert('RGB')
        old = old.resize((old.width * 2, old.height * 2), Image.NEAREST)
        img.paste(old, (x + 4, y + 4))
        ico = Image.open(os.path.join(OUT, snake(e['fluent']) + '.ico'))
        for k, size in enumerate((16, 24, 48)):
            ico.size = (size, size)
            im = ico.convert('RGBA')
            img.paste(im, (x + 64 + k * 30 if size < 48 else x + 124, y + 4), im)
        d.text((x + 180, y + 6), e['resource'], fill=(160, 0, 0))
        d.text((x + 180, y + 22), e['fluent'], fill=(0, 0, 0))
        d.text((x + 4, y + 50), e['used by'][:46], fill=(80, 80, 80))
    img.save(os.path.join(OUT, 'sheet.png'))


if __name__ == '__main__':
    if len(sys.argv) != 3 or sys.argv[1] not in ('fetch', 'build'):
        sys.exit(__doc__)
    (fetch if sys.argv[1] == 'fetch' else build)(os.path.abspath(sys.argv[2]))
